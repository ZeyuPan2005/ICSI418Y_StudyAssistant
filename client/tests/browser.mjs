  // Drive the focus sequence with real key presses. Supply the selected file
  // through Playwright at the operating-system chooser boundary.
  async function tabTo(target) {
    for (let i = 0; i < 100; i++) {
      if (await target.evaluate(node => node === document.activeElement)) return
      await page.keyboard.press('Tab')
    }
    throw Error('Keyboard focus did not reach the target.')
  }
  async function activate(target) {
    await tabTo(target)
    await page.keyboard.press('Enter')
  }
